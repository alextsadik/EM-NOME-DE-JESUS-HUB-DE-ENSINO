export function getMedalsProgress(stats: PlayerStats): ReconciliationMedal[] {
  return RECONCILIATION_MEDALS_DATA.map((base) => {
    let currentValue = 0;

    switch (base.id) {
      case 'guerreiro_da_fe':
        currentValue = stats.strongmanBoundCount || 0;
        break;
      case 'arauto_da_graca':
        currentValue = stats.proclaimedDecreesCount || 0;
        break;
      case 'embaixador_reconciliacao':
        currentValue = stats.reconciledCount || 0;
        break;
      case 'sentinela_maranata':
        currentValue = stats.maranataProclaimedCount || 0;
        break;
      case 'mestre_cristocentrico':
        currentValue = stats.sermonsDeliveredCount || 0;
        break;
      case 'praticante_colossenses':
        currentValue = stats.completedMissions ? stats.completedMissions.length : 0;
        break;
      case 'amigo_das_hostes':
        currentValue = stats.angelicAidInvokedCount || 0;
        break;
      case 'fruto_maduro':
        currentValue = (stats.fruits?.fidelidade || 0) + (stats.fruits?.amor || 0);
        break;
      default:
        currentValue = 0;
    }

    const isUnlocked = currentValue >= base.targetCount;

    return {
      ...base,
      currentValue,
      isUnlocked,
    };
  });
}

