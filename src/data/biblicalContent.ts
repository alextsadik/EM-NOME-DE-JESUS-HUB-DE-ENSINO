export function getWorshiperTier(points: number): WorshipTierDefinition {
  if (points >= 8000) return WORSHIP_TIERS_CONFIG.adorador_eterno;
  if (points >= 5000) return WORSHIP_TIERS_CONFIG.coluna;
  if (points >= 3000) return WORSHIP_TIERS_CONFIG.salmista;
  if (points >= 1500) return WORSHIP_TIERS_CONFIG.levita;
  if (points >= 500) return WORSHIP_TIERS_CONFIG.cantor;
  return WORSHIP_TIERS_CONFIG.vigia;
}

export function calculateWorshipScore(stats: PlayerStats): number {
  const radioPts = (stats.radioListeningMinutes || 0) * 10;
  const challengePts = (stats.completedPraiseChallengesCount || 0) * 150;
  const medPts = (stats.meditationMinutes || 0) * 20;
  const calculated = radioPts + challengePts + medPts;
  return Math.max(calculated, stats.worshipScore || 0);
}

